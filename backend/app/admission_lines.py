def _seed_all(db: Session) -> int:
    added = 0
    for category, school, code, score, note in ZHONGKAO_LINES_2026:
        db.add(models.AdmissionLine(
            exam_type="zhongkao", region="苏州", year=2026,
            category=category, track="", province="苏州", school=school, code=code,
            score=score, note=note,
        ))
        added += 1
    for school, code, score, note in ZHONGKAO_CONTROL_LINES_2026:
        db.add(models.AdmissionLine(
            exam_type="zhongkao", region="苏州", year=2026,
            category="控制线", track="", province="苏州", school=school, code=code,
            score=score, note=note,
        ))
        added += 1
    for school, code, score, note in ZHONGKAO_REFERENCE_LINES:
        db.add(models.AdmissionLine(
            exam_type="zhongkao", region="苏州", year=2025,
            category="控制线", track="", province="苏州", school=school, code=code,
            score=score, note=note,
        ))
        added += 1

    for school, code, hist, phys, note in GAOKAO_LINES_2026:
        for track, score in (("历史类", hist), ("物理类", phys)):
            if score is None:
                continue
            db.add(models.AdmissionLine(
                exam_type="gaokao", region="江苏", year=2026,
                category="本科批投档线", track=track, province=("江苏" if school in JIANGSU_SCHOOLS else ""),
                school=school,
                code=code, score=score, note=note,
            ))
            added += 1
    for category, track, score, note in GAOKAO_CONTROL_LINES_2026:
        db.add(models.AdmissionLine(
            exam_type="gaokao", region="江苏", year=2026,
            category=category, track=track, province="", school=category,
            code="", score=score, note=note,
        ))
        added += 1
    return added


def seed_admission_lines(db: Session) -> int:
    """按版本维护分数线：表为空则写入；内置版本升级时清空重写（用户新增行会随版本
    升级被覆盖，可在前端重新维护）。"""
    ver = ""
    row = db.query(models.AppSetting).filter(models.AppSetting.key == "admission_lines_version").first()
    if row:
        ver = row.value
    existing = db.query(models.AdmissionLine).count()
    if existing > 0 and ver == ADMISSION_LINES_VERSION:
        return 0
    if existing > 0:
        db.query(models.AdmissionLine).delete()
    added = _seed_all(db)
    if row:
        row.value = ADMISSION_LINES_VERSION
    else:
        db.add(models.AppSetting(key="admission_lines_version", value=ADMISSION_LINES_VERSION))
    db.commit()
    return added
